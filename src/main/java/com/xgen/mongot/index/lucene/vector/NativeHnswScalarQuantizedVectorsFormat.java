package com.xgen.mongot.index.lucene.vector;

import static com.xgen.mongot.index.lucene.vector.Lucene99NativeHnswVectorsFormat.DEFAULT_HNSW_GRAPH_THRESHOLD;
import static org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsFormat.DEFAULT_BEAM_WIDTH;
import static org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsFormat.DEFAULT_MAX_CONN;
import static org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsFormat.DEFAULT_NUM_MERGE_WORKER;
import static org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsFormat.MAXIMUM_BEAM_WIDTH;
import static org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsFormat.MAXIMUM_MAX_CONN;

import com.google.auto.service.AutoService;
import com.xgen.mongot.index.definition.VectorFieldSpecification;
import java.io.IOException;
import java.util.Optional;
import java.util.concurrent.ExecutorService;
import org.apache.lucene.codecs.KnnVectorsFormat;
import org.apache.lucene.codecs.KnnVectorsReader;
import org.apache.lucene.codecs.KnnVectorsWriter;
import org.apache.lucene.codecs.hnsw.FlatVectorsFormat;
import org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsFormat;
import org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsReader;
import org.apache.lucene.codecs.lucene99.Lucene99HnswVectorsWriter;
import org.apache.lucene.index.SegmentReadState;
import org.apache.lucene.index.SegmentWriteState;
import org.apache.lucene.search.TaskExecutor;
import org.apache.lucene.util.hnsw.HnswGraph;

/**
 * A drop-in replacement for {@code Lucene99HnswScalarQuantizedVectorsFormat} that substitutes
 * {@link NativeScalarQuantizedVectorsScorer} (via {@link NativeScalarQuantizedFlatVectorsFormat})
 * so that 7-bit scalar-quantized byte vectors are scored with native SIMD when the dynamic feature
 * flag is enabled and the hardware is accelerated.
 *
 * <p>The codec name is kept as {@code "Lucene99HnswScalarQuantizedVectorsFormat"} so that segments
 * written by this format are read back transparently by Lucene's standard reader chain, and so
 * enabling or disabling native scoring requires no reindex.
 *
 * <p>This shares its on-disk name with stock {@code Lucene99HnswScalarQuantizedVectorsFormat}, so
 * both self-registering via {@code @AutoService} would make {@code KnnVectorsFormat.forName()}
 * resolution classpath-order-dependent. {@code bazel/java/spi_service_overrides.tsv} strips the
 * stock entry from the packaged binary's SPI service file at stamp time, making this class the
 * deterministic, sole provider of the name on the read path; see {@code
 * scripts/deploy/apply_spi_service_overrides.sh}.
 */
@AutoService(KnnVectorsFormat.class)
public class NativeHnswScalarQuantizedVectorsFormat extends KnnVectorsFormat {

  /**
   * Controls how many of the nearest neighbor candidates are connected to the new node. See {@link
   * HnswGraph} for more details.
   */
  private final int maxConn;

  /**
   * The number of candidate neighbors to track while searching the graph for each newly inserted
   * node. See {@link HnswGraph} for details.
   */
  private final int beamWidth;

  /** The format for storing, reading, and merging vectors on disk. */
  private final FlatVectorsFormat flatVectorsFormat;

  private final int numMergeWorkers;
  private final Optional<TaskExecutor> mergeExec;

  /** Tiny-segment graph threshold and graph write version; see {@link HnswWriteParams}. */
  private final HnswWriteParams hnswWriteParams;

  /** Constructs a format using default graph construction parameters. */
  public NativeHnswScalarQuantizedVectorsFormat() {
    this(
        DEFAULT_MAX_CONN,
        DEFAULT_BEAM_WIDTH,
        DEFAULT_NUM_MERGE_WORKER,
        Optional.empty(),
        new HnswWriteParams(DEFAULT_HNSW_GRAPH_THRESHOLD, Lucene99HnswVectorsFormat.VERSION_START));
  }

  /**
   * Constructs a format using the given graph construction parameters.
   *
   * @param maxConn the maximum number of connections to a node in the HNSW graph
   * @param beamWidth the size of the queue maintained during graph construction
   */
  public NativeHnswScalarQuantizedVectorsFormat(int maxConn, int beamWidth) {
    this(
        maxConn,
        beamWidth,
        DEFAULT_NUM_MERGE_WORKER,
        Optional.empty(),
        new HnswWriteParams(DEFAULT_HNSW_GRAPH_THRESHOLD, Lucene99HnswVectorsFormat.VERSION_START));
  }

  /**
   * Constructs a format using the given graph construction parameters.
   *
   * @param maxConn the maximum number of connections to a node in the HNSW graph
   * @param beamWidth the size of the queue maintained during graph construction
   * @param numMergeWorkers number of workers (threads) used when merging. If larger than 1, a
   *     non-empty {@link ExecutorService} must be supplied.
   * @param mergeExec the {@link ExecutorService} used by writers generated by this format to merge
   * @param hnswWriteParams the tiny-segment graph threshold and graph write version
   */
  public NativeHnswScalarQuantizedVectorsFormat(
      int maxConn,
      int beamWidth,
      int numMergeWorkers,
      Optional<ExecutorService> mergeExec,
      HnswWriteParams hnswWriteParams) {
    super("Lucene99HnswScalarQuantizedVectorsFormat");
    if (maxConn <= 0 || maxConn > MAXIMUM_MAX_CONN) {
      throw new IllegalArgumentException(
          "maxConn must be positive and less than or equal to "
              + MAXIMUM_MAX_CONN
              + "; maxConn="
              + maxConn);
    }
    if (beamWidth <= 0 || beamWidth > MAXIMUM_BEAM_WIDTH) {
      throw new IllegalArgumentException(
          "beamWidth must be positive and less than or equal to "
              + MAXIMUM_BEAM_WIDTH
              + "; beamWidth="
              + beamWidth);
    }
    this.maxConn = maxConn;
    this.beamWidth = beamWidth;
    if (numMergeWorkers < 1) {
      throw new IllegalArgumentException(
          "numMergeWorkers must be positive; numMergeWorkers=" + numMergeWorkers);
    }
    if (numMergeWorkers == 1 && mergeExec.isPresent()) {
      throw new IllegalArgumentException(
          "No executor service is needed as we'll use single thread to merge");
    }
    if (numMergeWorkers > 1 && mergeExec.isEmpty()) {
      throw new IllegalArgumentException(
          "An executor service is required when using more than one merge worker");
    }
    this.numMergeWorkers = numMergeWorkers;
    this.mergeExec = mergeExec.map(TaskExecutor::new);
    this.hnswWriteParams = hnswWriteParams;
    this.flatVectorsFormat = new NativeScalarQuantizedFlatVectorsFormat();
  }

  @Override
  public KnnVectorsWriter fieldsWriter(SegmentWriteState state) throws IOException {
    return new Lucene99HnswVectorsWriter(
        state,
        this.maxConn,
        this.beamWidth,
        this.flatVectorsFormat.fieldsWriter(state),
        this.numMergeWorkers,
        this.mergeExec.orElse(null),
        this.hnswWriteParams.tinySegmentsThreshold(),
        this.hnswWriteParams.graphWriteVersion());
  }

  @Override
  public KnnVectorsReader fieldsReader(SegmentReadState state) throws IOException {
    return new Lucene99HnswVectorsReader(state, this.flatVectorsFormat.fieldsReader(state));
  }

  @Override
  public int getMaxDimensions(String fieldName) {
    return VectorFieldSpecification.MAX_DIMENSIONS;
  }

  @Override
  public String toString() {
    return "NativeHnswScalarQuantizedVectorsFormat("
        + "name=Lucene99HnswScalarQuantizedVectorsFormat, maxConn="
        + this.maxConn
        + ", beamWidth="
        + this.beamWidth
        + ", flatVectorsFormat="
        + this.flatVectorsFormat
        + ")";
  }
}
